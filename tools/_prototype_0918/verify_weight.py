import sys


def 기하자중(elems, γ, b=1.0):
    """elems: [(id, n1, n2, θ, t, ℓ)] → 자중 합 [kN]"""
    return sum(t * b * ℓ * γ for (_, _, _, _, t, ℓ) in elems)


def 대조(계산값, NX값, 허용=1e-3, 이름="자중"):
    """
    상대오차가 허용치를 넘으면 실패로 돌려준다.
    교량 절차의 허용오차 1e-3 을 그대로 쓴다(지점 가로보 누락 같은 것을 잡던 값).
    """
    if 계산값 == 0:
        오차 = abs(NX값)
    else:
        오차 = abs(NX값 - 계산값) / abs(계산값)
    통과 = 오차 <= 허용
    return {
        "이름": 이름, "계산값": 계산값, "NX값": NX값,
        "상대오차": 오차, "허용": 허용, "통과": 통과,
        "문구": "%s: 계산 %.4f / NX %.4f / 오차 %.3e → %s" % (
            이름, 계산값, NX값, 오차, "OK" if 통과 else "불일치"),
    }


def 단면대조(t, b, NX_I, 허용=1e-4):
    """NX 에서 읽은 I 를 직사각 단면 계산값과 대조한다. H·B 뒤집힘 탐지용."""
    I계산 = b * t ** 3 / 12.0
    r = 대조(I계산, NX_I, 허용, "단면2차모멘트 t=%.3f" % t)
    if not r["통과"]:
        I뒤집힘 = t * b ** 3 / 12.0
        if abs(NX_I - I뒤집힘) / max(I뒤집힘, 1e-12) < 허용:
            r["문구"] += "  ← H·B 가 뒤집혔다. section_rect(H=%.3f, B=%.3f) 순서 확인" % (t, b)
    return r


